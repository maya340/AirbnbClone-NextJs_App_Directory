import "./globals.css";
import ReduxProvider from "../../providers/RedusProvider";
import Header from "../../components/header";
import Footer from "../../components/footer";
import { Directions, Languages } from "@/src/constans/enum";
import { Metadata } from "next";
import { Inter, Roboto } from "next/font/google";
import { cn } from "cn";

export function generateStaticParams() {
  return [{ locale: Languages.ENGLISH }, { locale: Languages.ARABIC }];
}

const inter = Inter({ subsets: ["latin"], variable: "--font-sans" });

const roboto = Roboto({
  subsets: ["latin"],
  weight: ["400", "500", "700"],
  preload: true,
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
  params,
}: Readonly<{
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}>) {
  const locale = (await params).locale;
  return (
    <html
      lang={locale}
      dir={locale === "ar" ? Directions.RTL : Directions.LTR}
      className={cn(roboto.className, "font-sans", inter.variable)}
    >
      <body className="min-h-full flex flex-col">
        {" "}
        <ReduxProvider>
          <Header />
          {children}
          <Footer />
        </ReduxProvider>
      </body>
    </html>
  );
}
